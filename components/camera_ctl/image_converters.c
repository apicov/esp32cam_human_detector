static const char* TAG = "img_conv";

// Working buffer for JPEG decoder (3.1KB as used in ESP32-Camera)
static uint8_t work_buffer[3100];

bool jpeg_to_rgb888(const uint8_t *jpeg_data, size_t jpeg_len, 
                    uint8_t *rgb_buf, uint16_t max_width, uint16_t max_height,
                    uint16_t *actual_width, uint16_t *actual_height) {
    
    if (jpeg_data == NULL || rgb_buf == NULL) {
        ESP_LOGE(TAG, "NULL input parameters");
        return false;
    }
    
    if (jpeg_len == 0) {
        ESP_LOGE(TAG, "Zero JPEG length");
        return false;
    }
    
    // Calculate maximum output buffer size
    uint32_t max_output_size = max_width * max_height * 3; // RGB888 = 3 bytes per pixel
    
    esp_jpeg_image_cfg_t jpeg_cfg = {
        .indata = (uint8_t *)jpeg_data,
        .indata_size = jpeg_len,
        .outbuf = rgb_buf,
        .outbuf_size = max_output_size,
        .out_format = JPEG_IMAGE_FORMAT_RGB888,
        .out_scale = JPEG_IMAGE_SCALE_0,  // No scaling
        .flags.swap_color_bytes = 0,
        .advanced.working_buffer = work_buffer,
        .advanced.working_buffer_size = sizeof(work_buffer),
    };
    
    esp_jpeg_image_output_t output_img = {};
    
    ESP_LOGD(TAG, "Decoding JPEG: %zu bytes -> RGB888", jpeg_len);
    
    esp_err_t ret = esp_jpeg_decode(&jpeg_cfg, &output_img);
    if (ret != ESP_OK) {
        ESP_LOGE(TAG, "JPEG decode failed: %s", esp_err_to_name(ret));
        return false;
    }
    
    // Return actual dimensions
    if (actual_width) {
        *actual_width = output_img.width;
    }
    if (actual_height) {
        *actual_height = output_img.height;
    }
    
    ESP_LOGI(TAG, "JPEG decoded successfully: %dx%d -> RGB888", 
             output_img.width, output_img.height);
    
    return true;
}

