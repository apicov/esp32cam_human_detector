#define YUYV_CONSTRAIN(v) ((v)<0)?0:(((v)>255)?255:(v))

void yuv2rgb(uint8_t y, uint8_t u, uint8_t v, uint8_t *r, uint8_t *g, uint8_t *b) {
    int16_t ri, gi, bi;

    ri = yuv_table[y].vY + yuv_table[v].vVr;
    gi = yuv_table[y].vY + yuv_table[u].vUg + yuv_table[v].vVg;
    bi = yuv_table[y].vY + yuv_table[u].vUb;

    *r = YUYV_CONSTRAIN(ri);
    *g = YUYV_CONSTRAIN(gi);
    *b = YUYV_CONSTRAIN(bi);
}

void rgb565_to_rgb888(uint16_t rgb565, uint8_t *r, uint8_t *g, uint8_t *b) {
    *r = (rgb565 >> 11) << 3;           // 5 bits -> 8 bits
    *g = ((rgb565 >> 5) & 0x3F) << 2;   // 6 bits -> 8 bits  
    *b = (rgb565 & 0x1F) << 3;          // 5 bits -> 8 bits
}

uint16_t rgb888_to_rgb565(uint8_t r, uint8_t g, uint8_t b) {
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3);
}